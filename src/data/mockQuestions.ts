// Перемішує варіанти відповідей питання (правильна відповідь залишається правильной).
export function shuffleQuestionOptions(q: Question): Question {
  const options = [...q.options];
  const correct = options.splice(q.correctIndex, 1)[0];
  for (let i = options.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [options[i], options[j]] = [options[j], options[i]];
  }
  options.splice(Math.floor(Math.random() * (options.length + 1)), 0, correct);
  const correctIndex = options.indexOf(correct);
  return { ...q, options, correctIndex };
}

// Повертає count питань з обраного предмета (за вибором теми — фільтр, інакше випадково).
// count за замовчуванням 3, може бути 5, 10 або більше.
export function pickMockQuestions(subject: Subject, topic: string | null, count: number = 3): Question[] {
  let pool = MOCK_QUESTIONS[subject];
  if (topic) {
    const filtered = pool.filter((q) => q.topic === topic);
    if (filtered.length >= 3) pool = filtered;
  }
  // якщо потрібні більше питань, ніж є в пулі — повторюємо випадково
  const needed = Math.max(count, 1);
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  const result: Question[] = [];
  const used = new Set<string>();
  // спочатку беремо унікальні
  for (const q of shuffled) {
    if (result.length >= needed) break;
    const key = q.id;
    if (!used.has(key)) {
      used.add(key);
      result.push(q);
    }
  }
  // якщо не вистачило унікальних — додаємо з повтореннями
  while (result.length < needed) {
    const q = shuffled[Math.floor(Math.random() * shuffled.length)];
    result.push(q);
  }
  // перемішуємо варіанти відповідей для кожного питання
  return result.map(shuffleQuestionOptions);
}
